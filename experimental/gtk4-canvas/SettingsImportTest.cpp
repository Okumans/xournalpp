#include <cmath>
#include <cstdlib>
#include <filesystem>
#include <fstream>
#include <iostream>
#include <string>

#include <unistd.h>

#include "SettingsImport.h"

namespace {

void require(bool condition, const char* message) {
    if (!condition) {
        std::cerr << "FAIL: " << message << '\n';
        std::exit(1);
    }
}

bool near(double a, double b) { return std::abs(a - b) < 1e-6; }

}  // namespace

int main() {
    // 1. Realistic GTK 3 Xournal++ settings.xml including XML prolog, comments,
    // <property name="font" .../> (no value attr), buttonConfig (must not collide
    // with tools), alpha-prefixed hex colors, and discrete tool sizes.
    const auto fullParsed = prototype::parseSettingsXml(R"xml(<?xml version="1.0" encoding="UTF-8"?>
<!--The Xournal++ settings file. Do not edit this file!-->
<settings>
  <property name="font" font="Sans" size="12"/>
  <property name="preferredLocale" value="fr_FR"/>
  <property name="pressureSensitivity" value="true"/>
  <property name="minimumPressure" value="0.14"/>
  <property name="pressureMultiplier" value="1.35"/>
  <property name="zoomStep" value="25.00000000"/>
  <property name="zoomStepScroll" value="4.50000000"/>
  <property name="edgePanSpeed" value="37"/>
  <property name="edgePanMaxMult" value="2.5"/>
  <property name="snapRotation" value="false"/>
  <property name="snapRotationTolerance" value="0.65"/>
  <property name="snapGrid" value="false"/>
  <property name="snapGridSize" value="28.5"/>
  <property name="snapGridTolerance" value="0.25"/>
  <property name="highlightPosition" value="true"/>
  <property name="cursorHighlightColor" value="2148606515"/>
  <property name="cursorHighlightRadius" value="18.5"/>
  <property name="cursorHighlightBorderColor" value="1075987558"/>
  <property name="cursorHighlightBorderWidth" value="3"/>
  <property name="strokeRecognizerMinSize" value="32"/>
  <property name="stabilizerAveragingMethod" value="2"/>
  <property name="stabilizerPreprocessor" value="1"/>
  <property name="stabilizerBuffersize" value="24"/>
  <property name="stabilizerSigma" value="0.65"/>
  <property name="stabilizerDeadzoneRadius" value="2.5"/>
  <property name="stabilizerCuspDetection" value="false"/>
  <property name="stabilizerDrag" value="0.25"/>
  <property name="stabilizerMass" value="6"/>
  <property name="stabilizerFinalizeStroke" value="false"/>
  <property name="showSidebar" value="false"/>
  <property name="themeVariant" value="forceDark"/>
  <property name="autosaveEnabled" value="true"/>
  <property name="autosaveTimeout" value="7"/>
  <property name="laserPointerFadeOutTime" value="750"/>
  <property name="audioFolder" value="recordings"/>
  <property name="defaultSeekTime" value="9"/>
  <property name="disableAudio" value="true"/>
  <property name="colorPalette" value="palettes/xournalpp.gpl"/>
  <property name="pluginEnabled" value="/plugins/ColorCycle"/>
  <property name="pluginDisabled" value="/plugins/Example"/>
  <data name="buttonConfig">
    <data name="eraser">
      <attribute name="tool" type="string" value="eraser"/>
      <attribute name="size" type="string" value="VERY_FINE"/>
      <attribute name="eraserMode" type="string" value="whiteout"/>
    </data>
  </data>
  <data name="tools">
    <attribute name="current" type="string" value="highlighter"/>
    <data name="pen">
      <attribute name="color" type="hex" value="ff002e99"/>
      <attribute name="size" type="string" value="BIG"/>
      <attribute name="fill" type="int" value="1"/>
      <attribute name="fillAlpha" type="int" value="192"/>
      <attribute name="style" type="string" value="dashdot"/>
    </data>
    <data name="highlighter">
      <attribute name="color" type="int" value="16753152"/>
      <attribute name="size" type="string" value="VERY_BIG"/>
      <attribute name="fill" type="int" value="0"/>
      <attribute name="fillAlpha" type="int" value="64"/>
    </data>
    <data name="eraser">
      <attribute name="size" type="string" value="THIN"/>
      <attribute name="type" type="string" value="deleteStroke"/>
    </data>
    <data name="text">
      <attribute name="align" type="int" value="2"/>
      <attribute name="justify" type="bool" value="true"/>
    </data>
    <data name="laserPointerPen">
      <attribute name="color" type="hex" value="ffff7f00"/>
      <attribute name="size" type="string" value="VERY_FINE"/>
    </data>
    <data name="laserPointerHighlighter">
      <attribute name="color" type="int" value="255"/>
      <attribute name="size" type="string" value="VERY_BIG"/>
    </data>
  </data>
</settings>
)xml");
    require(fullParsed.ok, "Valid GTK 3 settings.xml failed to parse");
    const auto& s = fullParsed.settings;
    require(s.activeTool == prototype::Tool::Highlighter, "activeTool mismatch");
    require(near(s.penColor[0], 0.0) && near(s.penColor[1], 0x2e / 255.0) && near(s.penColor[2], 0x99 / 255.0),
            "Alpha-prefixed hex pen color mismatch");
    require(near(s.penWidth, 2.26), "BIG pen preset should map to 2.26pt");
    require(s.penFillEnabled && s.penFillOpacity == 192 && !s.highlighterFillEnabled &&
                    s.penLineStyle == "dashdot" &&
                    s.highlighterFillOpacity == 64,
            "Per-tool fill enablement and opacity settings were not imported");
    // 16753152 == 0xFFA200
    require(near(s.highlighterColor[0], 1.0) && near(s.highlighterColor[1], 0xa2 / 255.0) &&
                    near(s.highlighterColor[2], 0.0),
            "Decimal int highlighter color mismatch");
    require(near(s.highlighterWidth, 30.0), "VERY_BIG highlighter preset should map to 30.0pt");
    require(near(s.eraserWidth, 2.83) && s.eraserMode == prototype::EraserMode::DeleteStroke,
            "Eraser THIN width or deleteStroke mode mismatch (or collided with buttonConfig)");
    require(near(s.laserPenColor[0], 1.0) && near(s.laserPenColor[1], 0x7f / 255.0) &&
                    near(s.laserPenColor[2], 0.0) && near(s.laserPenWidth, 0.7),
            "Laser Pointer Pen color or VERY_FINE width mismatch");
    require(near(s.laserHighlighterColor[0], 0.0) && near(s.laserHighlighterColor[1], 0.0) &&
                    near(s.laserHighlighterColor[2], 1.0) && near(s.laserHighlighterWidth, 30.0),
            "Laser Pointer Highlighter color or VERY_BIG width mismatch");
    require(s.laserPointerFadeOutTimeMs == 750, "Laser pointer fade delay mismatch");
    require(s.audioFolder == std::filesystem::path("recordings") && s.defaultSeekTimeSeconds == 9 && s.disableAudio,
            "Audio playback settings were not imported");
    require(s.pluginsEnabled == "/plugins/ColorCycle" && s.pluginsDisabled == "/plugins/Example",
            "Legacy plugin enablement settings were not imported");
    require(s.pressureSensitivity && near(s.minimumPressure, 0.14) && near(s.pressureMultiplier, 1.35),
            "Pressure settings mismatch");
    require(near(s.zoomStep, 0.25) && near(s.scrollZoomStep, 0.045), "Zoom percent-to-fraction conversion mismatch");
    require(near(s.edgePanSpeed, 37) && near(s.edgePanMaxMultiplier, 2.5),
            "Selection edge-pan settings were not imported");
    require(near(s.snapRotationTolerance, 0.65), "Selection rotation tolerance import mismatch");
    require(!s.snapRotation, "Selection rotation snapping preference import mismatch");
    require(!s.snapGrid && near(s.snapGridSize, 28.5) && near(s.snapGridTolerance, 0.25),
            "Page-grid snapping preferences did not import");
    require(s.highlightPosition && s.cursorHighlightColor == 0x80112233U && near(s.cursorHighlightRadius, 18.5) &&
                    s.cursorHighlightBorderColor == 0x40224466U && near(s.cursorHighlightBorderWidth, 3),
            "Pointer highlight settings did not import");
    require(near(s.shapeRecognizerMinSize, 32) &&
                    s.stabilizer.averaging == prototype::AveragingMethod::VelocityGaussian &&
                    s.stabilizer.preprocessor == prototype::StrokePreprocessor::Deadzone &&
                    s.stabilizer.bufferSize == 24 && near(s.stabilizer.sigma, 0.65) &&
                    near(s.stabilizer.deadzoneRadius, 2.5) && !s.stabilizer.cuspDetection &&
                    near(s.stabilizer.drag, 0.25) && near(s.stabilizer.mass, 6) &&
                    !s.stabilizer.finalizeStroke,
            "Shape recognizer or stroke stabilizer settings mismatch");
    prototype::CanvasState importedState;
    prototype::applyImportedSettingsToCanvas(importedState, s);
    require(near(importedState.shapeRecognizerMinSize, 32), "Shape recognizer minimum size was not applied to canvas state");
    require(near(importedState.snapRotationTolerance, 0.65), "Rotation tolerance was not applied to canvas state");
    require(near(importedState.edgePanSpeed, 37) && near(importedState.edgePanMaxMultiplier, 2.5),
            "Selection edge-pan settings were not applied to canvas state");
    require(!importedState.snapRotationEnabled, "Rotation snapping setting was not applied to canvas state");
    require(importedState.laserFadeOutTimeMs == 750, "Laser pointer fade delay was not applied to canvas state");

    const auto laserActive = prototype::parseSettingsXml(R"xml(<settings><data name="tools">
  <attribute name="current" type="string" value="laserPointerHighlighter"/>
</data></settings>)xml");
    require(laserActive.ok && laserActive.settings.activeTool == prototype::Tool::LaserPointerHighlighter,
            "Active Laser Pointer Highlighter setting was not imported");
    require(!importedState.snapGridEnabled && near(importedState.snapGridSize, 28.5) &&
                    near(importedState.snapGridTolerance, 0.25),
            "Page-grid snapping preferences were not applied to canvas state");
    require(!s.showSidebar && s.themeVariant == prototype::ThemeVariant::ForceDark,
            "showSidebar or forceDark mismatch");
    require(s.autosaveEnabled && s.autosaveTimeoutMinutes == 7 && s.effectiveAutosaveSeconds() == 420,
            "autosaveTimeout minutes-to-seconds conversion mismatch");
    require(s.colorPalettePath == std::filesystem::path("palettes/xournalpp.gpl"), "colorPalettePath mismatch");
    require(s.textFontName == "Sans" && near(s.textFontSize, 12), "Text font import mismatch");
    require(s.textAlignment == 2 && s.textJustify, "Text alignment and justification import mismatch");
    require(importedState.textAlignment == 2 && importedState.textJustify,
            "Text alignment and justification were not applied to canvas state");

    // 2. Legacy bugs fixed:
    //    - presureSensitivity typo honored; minimumPressure < 0.01 clamped to 0.01;
    //    - missing name/type/value attributes on <data>/<attribute> do not dereference nullptr;
    //    - missing or unmigrated tools.current still loads per-tool settings;
    //    - disabled autosave maps effectiveAutosaveSeconds() to 0.
    const auto edgeParsed = prototype::parseSettingsXml(R"xml(
<settings>
  <property name="presureSensitivity" value="false"/>
  <property name="minimumPressure" value="0.0001"/>
  <property name="autosaveEnabled" value="false"/>
  <property name="themeVariant" value="forceLight"/>
  <data>
    <attribute name="orphan"/>
  </data>
  <data name="tools">
    <attribute name="current" type="string" value="selectRect"/>
    <attribute name="brokenNoType" value="foo"/>
    <data name="pen">
      <attribute name="size" type="string" value="VERY_FINE"/>
      <attribute type="hex" value="00112233"/>
    </data>
    <data name="eraser">
      <attribute name="type" type="string" value="whiteout"/>
    </data>
  </data>
</settings>
)xml");
    require(edgeParsed.ok, "Edge-case settings.xml should parse without crashing");
    require(!edgeParsed.settings.pressureSensitivity, "Legacy presureSensitivity typo was not honored");
    require(near(edgeParsed.settings.minimumPressure, 0.01), "minimumPressure below 0.01 must clamp to 0.01");
    require(edgeParsed.settings.effectiveAutosaveSeconds() == 0, "Disabled autosave must yield 0 seconds");
    require(edgeParsed.settings.themeVariant == prototype::ThemeVariant::ForceLight, "forceLight mismatch");
    require(edgeParsed.settings.activeTool == prototype::Tool::Pen,
            "Unmigrated active tool should fall back to Tool::Pen");
    require(near(edgeParsed.settings.penWidth, 0.42),
            "Per-tool pen size must still load when current names an unmigrated tool");
    require(edgeParsed.settings.eraserMode == prototype::EraserMode::Whiteout,
            "Per-tool eraser mode must still load when current names an unmigrated tool");

    const auto objectToolParsed = prototype::parseSettingsXml(
            "<settings><data name=\"tools\"><attribute name=\"current\" type=\"string\" "
            "value=\"selectObject\"/></data></settings>");
    require(objectToolParsed.ok && objectToolParsed.settings.activeTool == prototype::Tool::SelectObject,
            "The current Select Object tool was not restored from settings.xml");

    const auto handToolParsed = prototype::parseSettingsXml(
            "<settings><data name=\"tools\"><attribute name=\"current\" type=\"string\" "
            "value=\"hand\"/></data></settings>");
    require(handToolParsed.ok && handToolParsed.settings.activeTool == prototype::Tool::Hand,
            "The current Hand tool was not restored from settings.xml");

    const auto latexSettingsParsed = prototype::parseSettingsXml(
            "<settings><property name=\"latexSettings.defaultText\" value=\"\\alpha\"/>"
            "<property name=\"latexSettings.globalTemplatePath\" value=\"/tmp/formula.tex\"/>"
            "<property name=\"latexSettings.genCmd\" value=\"tectonic '{}'\"/>"
            "<property name=\"latexSettings.autoCheckDependencies\" value=\"false\"/>"
            "<property name=\"latexSettings.sourceViewThemeId\" value=\"Adwaita-dark\"/>"
            "<property name=\"latexSettings.sourceViewAutoIndent\" value=\"false\"/>"
            "<property name=\"latexSettings.sourceViewSyntaxHighlight\" value=\"false\"/>"
            "<property name=\"latexSettings.sourceViewShowLineNumbers\" value=\"true\"/>"
            "<property name=\"latexSettings.editorFont\" font=\"Monospace\" size=\"15\"/>"
            "<property name=\"latexSettings.useCustomEditorFont\" value=\"true\"/>"
            "<property name=\"latexSettings.editorWordWrap\" value=\"false\"/>"
            "<property name=\"latexSettings.useExternalEditor\" value=\"true\"/>"
            "<property name=\"latexSettings.externalEditorAutoConfirm\" value=\"true\"/>"
            "<property name=\"latexSettings.externalEditorCmd\" value=\"code --wait\"/>"
            "<property name=\"latexSettings.temporaryFileExt\" value=\"ltx\"/>"
            "<data name=\"tools\"><attribute name=\"current\" type=\"string\" value=\"latex\"/></data>"
            "<data name=\"latex\"><attribute name=\"color\" type=\"hex\" value=\"ff123456\"/>"
            "</data></settings>");
    require(latexSettingsParsed.ok && latexSettingsParsed.settings.activeTool == prototype::Tool::Latex &&
                    latexSettingsParsed.settings.latexDefaultText == "\\alpha" &&
                    latexSettingsParsed.settings.latexTemplatePath == "/tmp/formula.tex" &&
                    latexSettingsParsed.settings.latexGeneratorCommand == "tectonic '{}'" &&
                    !latexSettingsParsed.settings.latexAutoCheckDependencies &&
                    latexSettingsParsed.settings.latexSourceViewThemeId == "Adwaita-dark" &&
                    !latexSettingsParsed.settings.latexSourceViewAutoIndent &&
                    !latexSettingsParsed.settings.latexSourceViewSyntaxHighlight &&
                    latexSettingsParsed.settings.latexSourceViewShowLineNumbers &&
                    latexSettingsParsed.settings.latexEditorFont == "Monospace 15" &&
                    latexSettingsParsed.settings.latexUseCustomEditorFont &&
                    !latexSettingsParsed.settings.latexEditorWordWrap &&
                    latexSettingsParsed.settings.latexUseExternalEditor &&
                    latexSettingsParsed.settings.latexExternalEditorAutoConfirm &&
                    latexSettingsParsed.settings.latexExternalEditorCommand == "code --wait" &&
                    latexSettingsParsed.settings.latexTemporaryFileExtension == "ltx" &&
                    latexSettingsParsed.settings.latexColor == std::array<double, 3>{0x12 / 255.0, 0x34 / 255.0,
                                                                                    0x56 / 255.0},
            "LaTeX tool, generator, template, default source or color settings were not imported");

    // 3. Truncated/malformed XML rolls back transactionally to clean defaults.
    const auto truncated = prototype::parseSettingsXml(
            "<settings><property name=\"themeVariant\" value=\"forceDark\"/><data name=\"tools\">");
    require(!truncated.ok && truncated.settings.themeVariant == prototype::ThemeVariant::ForceDark,
            "Truncated XML must fail cleanly and roll back partial mutations");
    require(!prototype::parseSettingsXml("<wrongRoot/>").ok, "Non-<settings> root must be rejected");

    // 4. Filesystem import: strictly read-only, never creates missing directories/files,
    //    never mutates LANGUAGE environment variable, refuses symlinks, and resolves palettes.
    const char* langBeforePtr = std::getenv("LANGUAGE");
    const std::string langBefore = langBeforePtr ? langBeforePtr : "<unset>";

    const auto scratch = std::filesystem::temp_directory_path() /
                         ("xournalpp-settings-import-test-" + std::to_string(static_cast<long long>(::getpid())));
    std::filesystem::remove_all(scratch);

    const auto missingConfigDir = scratch / "does-not-exist";
    const auto missingImport = prototype::importSettingsFromConfigDir(missingConfigDir);
    require(!missingImport.foundSettingsFile && !missingImport.usedSettingsFallback &&
                    missingImport.palette.swatches.size() == 11 && !std::filesystem::exists(missingConfigDir),
            "Missing config dir must return defaults without creating directories or settings.xml");

    std::filesystem::create_directories(scratch / "valid" / "palettes");
    {
        std::ofstream gpl(scratch / "valid" / "palettes" / "custom.gpl", std::ios::binary);
        gpl << "GIMP Palette\nName: Imported GPL\n#\n10 20 30 Ink Navy\n200 100 50 Amber\n";
        std::ofstream xml(scratch / "valid" / "settings.xml", std::ios::binary);
        xml << "<settings>\n"
            << "  <property name=\"preferredLocale\" value=\"de_DE\"/>\n"
            << "  <property name=\"colorPalette\" value=\"custom.gpl\"/>\n"
            << "  <data name=\"tools\">\n"
            << "    <data name=\"pen\"><attribute name=\"size\" type=\"string\" value=\"BIG\"/></data>\n"
            << "  </data>\n"
            << "</settings>\n";
    }
    const auto validImport = prototype::importSettingsFromConfigDir(scratch / "valid");
    require(validImport.foundSettingsFile && !validImport.usedSettingsFallback && !validImport.palette.usedFallback &&
                    validImport.palette.paletteName == "Imported GPL" && validImport.palette.swatches.size() == 2 &&
                    near(validImport.settings.penWidth, 2.26),
            "Valid config directory failed to import settings.xml + custom.gpl");

    const char* langAfterPtr = std::getenv("LANGUAGE");
    const std::string langAfter = langAfterPtr ? langAfterPtr : "<unset>";
    require(langBefore == langAfter, "Settings import must never call setenv(\"LANGUAGE\", ...)");

    std::filesystem::create_directories(scratch / "symlinked");
    std::filesystem::create_symlink(scratch / "valid" / "settings.xml", scratch / "symlinked" / "settings.xml");
    const auto symlinkImport = prototype::importSettingsFromConfigDir(scratch / "symlinked");
    require(symlinkImport.foundSettingsFile && symlinkImport.usedSettingsFallback && !symlinkImport.warning.empty() &&
                    near(symlinkImport.settings.penWidth, 1.41),
            "Symlink settings.xml must be refused and fall back to defaults");

    std::filesystem::remove_all(scratch);
    return 0;
}
